"""Run expert-audited sequence, reliability and satellite-only distillation probes.

These are controlled first experiments; no neural temporal cross-attention is claimed.
One row per field-season, month-level ground timestamp and observed satellite sequence.
"""
import argparse
import json
from pathlib import Path
import warnings

import numpy as np
import pandas as pd
from sklearn.metrics import brier_score_loss, roc_auc_score
from sklearn.model_selection import GroupKFold
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from study_utils import (load_inputs, spatial_partition, block_ids, classifier,
                         probabilities, prediction_metrics, temporal_features,
                         confidence_features)


def audit(meta, split):
    """Descriptive analysis; counts reported even if no reliable VLM comparisons."""
    out = {
        "label_sources": {str(k):int(v) for k,v in meta.label_source.value_counts().items()},
        "capture_months": {str(k):int(v) for k,v in meta.capture_month.value_counts().sort_index().items()},
        "crop_counts": {str(k):int(v) for k,v in meta.crop_label.value_counts().items()},
        "expert_test_n": len(split["test"]),
        "vlm_vs_expert": None
    }
    if "vlm_label" in meta:
        gold = meta[meta.label_source == "expert"].copy()
        gold = gold[gold.vlm_label.notna()]
        if len(gold):
            gold["wrong"] = gold.vlm_label.astype(str) != gold.crop_label.astype(str)
            out["vlm_vs_expert"] = {
                "n": len(gold),
                "overall_error": float(gold.wrong.mean()),
                "by_month": {str(int(m)): {"n":len(s), "error_rate": float(s.wrong.mean())}
                             for m,s in gold.groupby("capture_month")},
                "by_crop": {str(c): {"n":len(s), "error_rate":float(s.wrong.mean())}
                            for c,s in gold.groupby("crop_label")}
            }
    if "image_field_match_audited" in meta:
        audited = meta.image_field_match_audited.dropna()
        if len(audited):
            out["audited_match_rate"] = float(pd.to_numeric(audited).mean())
            out["audited_match_n"] = int(len(audited))
    return out


def expert_indices(meta, indices):
    return indices[meta.label_source.to_numpy()[indices] == "expert"]


def model_probe(meta, ground, sat, observed, yearmonth, split, seed):
    labels = sorted(meta.crop_label.unique().astype(str))
    y = meta.crop_label.astype(str).to_numpy()
    train_gold = expert_indices(meta, split["train"])
    if len(train_gold) < 20 or len(np.unique(y[train_gold])) < 2:
        raise ValueError("Need >=20 expert-labelled train observations and >=2 classes.")
    models = {}
    fitted = {}
    variants = ["satellite", "ground", "concat", "satellite_plus_date",
                "concat_plus_date", "aligned", "aligned_no_date"]
    for variant in variants:
        X = temporal_features(meta,ground,sat,observed,yearmonth,variant)
        m = classifier().fit(X[train_gold],y[train_gold])
        fitted[variant] = m
        models[variant] = prediction_metrics(y[split["test"]],
                                             probabilities(m,X[split["test"]],labels),labels)
    # Negative control: shuffle capture month/year across fields, including its
    # relationship to satellite dates. Fit and evaluate a *new* model on shuffled
    # training timestamps, with an independently shuffled test timestamp.
    rng = np.random.default_rng(seed)
    shuffled = meta.copy()
    for group in (split["train"],split["val"],split["test"]):
        perm = rng.permutation(group)
        shuffled.loc[group,["capture_month","capture_year"]] = (
            meta.iloc[perm][["capture_month","capture_year"]].to_numpy())
    for variant in ("concat_plus_date","aligned"):
        X = temporal_features(shuffled,ground,sat,observed,yearmonth,variant)
        m = classifier().fit(X[train_gold],y[train_gold])
        models[variant+"_shuffled_timestamp"] = prediction_metrics(
            y[split["test"]],probabilities(m,X[split["test"]],labels),labels)
    return models, fitted, labels, train_gold


def oof_predictions(X, y, indices, groups, labels, n_splits=3):
    """Expert errors generated by geographically out-of-fold experts."""
    local_groups = groups[indices]
    k = min(n_splits,len(np.unique(local_groups)))
    if k < 3:
        raise ValueError("Need >=3 independent spatial training groups for OOF reliability")
    out = np.full((len(indices),len(labels)), np.nan)
    for train_ix, hold_ix in GroupKFold(n_splits=k).split(
            X[indices],y[indices],groups=local_groups):
        fitted_labels = y[indices[train_ix]]
        if len(np.unique(fitted_labels)) < 2:
            raise ValueError("Too few classes in an OOF training fold.")
        model = classifier().fit(X[indices[train_ix]],fitted_labels)
        out[hold_ix] = probabilities(model,X[indices[hold_ix]],labels)
    if not np.isfinite(out).all():
        raise AssertionError("Incomplete out-of-fold predictions")
    return out


def error_model(X, error):
    # Simple, inspectable estimator, not a neural gate.
    if len(np.unique(error)) < 2:
        return None
    return make_pipeline(StandardScaler(),
                         LogisticRegression(max_iter=1000, class_weight="balanced")).fit(X,error)


def estimate_error(model,X,default):
    if model is None:
        return np.full(len(X),default)
    return model.predict_proba(X)[:,list(model.classes_).index(1)]


def reliability_probe(meta, ground, sat, observed, yearmonth, split, fitted, labels, gold):
    """Compare OOF error-trained reliability estimates with naive fusion.

    Held-out expert labels are only used for evaluating risk and prediction.
    """
    y = meta.crop_label.astype(str).to_numpy()
    groups = block_ids(meta, 1.0)
    Xs = temporal_features(meta,ground,sat,observed,yearmonth,"satellite")
    Xg = temporal_features(meta,ground,sat,observed,yearmonth,"ground")
    ps = oof_predictions(Xs,y,gold,groups,labels)
    pg = oof_predictions(Xg,y,gold,groups,labels)
    encoded = {label:i for i,label in enumerate(labels)}
    true_ix = np.array([encoded[v] for v in y[gold]])
    es = (ps.argmax(1) != true_ix).astype(int)
    eg = (pg.argmax(1) != true_ix).astype(int)
    quality = meta.ground_quality.to_numpy(dtype=float)
    months = meta.capture_month.to_numpy(dtype=float)
    fs = confidence_features(ps,observed[gold],
                             quality[gold],months[gold])
    fg = confidence_features(pg,observed[gold],
                             quality[gold],months[gold])
    risk_sat = error_model(fs,es)
    risk_ground = error_model(fg,eg)
    tst = split["test"]
    pred_s = probabilities(fitted["satellite"],Xs[tst],labels)
    pred_g = probabilities(fitted["ground"],Xg[tst],labels)
    test_sat = confidence_features(pred_s,observed[tst],quality[tst],months[tst])
    test_ground = confidence_features(pred_g,observed[tst],quality[tst],months[tst])
    rs = estimate_error(risk_sat,test_sat,float(es.mean()))
    rg = estimate_error(risk_ground,test_ground,float(eg.mean()))
    # Compare fixed average, confidence-based weighting and OOF-risk weighting.
    weight_sat = np.exp(-rs / .25)
    weight_ground = np.exp(-rg / .25)
    ws = weight_sat / (weight_sat+weight_ground)
    risk_fused = ws[:,None]*pred_s + (1-ws[:,None])*pred_g
    confs = pred_s.max(1)
    confg = pred_g.max(1)
    wc = confs/np.maximum(confs+confg,1e-8)
    confidence_fused = wc[:,None]*pred_s + (1-wc[:,None])*pred_g
    yy = y[tst]
    actual_s = (pred_s.argmax(1) != np.array([encoded[v] for v in yy])).astype(int)
    actual_g = (pred_g.argmax(1) != np.array([encoded[v] for v in yy])).astype(int)
    def risk_metrics(actual,predicted):
        result = {"brier":float(brier_score_loss(actual,predicted)),
                  "actual_error_rate":float(actual.mean()),
                  "mean_predicted_error":float(predicted.mean())}
        if len(np.unique(actual)) > 1:
            result["error_detection_auc"]=float(roc_auc_score(actual,predicted))
        return result
    return {"satellite_risk":risk_metrics(actual_s,rs),
            "ground_risk":risk_metrics(actual_g,rg),
            "equal_weight":prediction_metrics(yy,.5*(pred_s+pred_g),labels),
            "confidence_weight":prediction_metrics(yy,confidence_fused,labels),
            "oof_risk_weight":prediction_metrics(yy,risk_fused,labels),
            "caution":"Per-sample OOF error targets use expert labels. Grouping is spatial. "
                      "Reported error calibration is preliminary, with no tuning on test."}


def soft_student(X, target_prob, labels, weights=None):
    """Train a satellite-only logistic student to soft pseudo-label distributions."""
    n,k = target_prob.shape
    if weights is None:
        weights = np.ones(n)
    # Soft-label cross-entropy equals weighted hard-class cross-entropy.
    model = make_pipeline(StandardScaler(),
                          LogisticRegression(max_iter=1500))
    row = np.repeat(np.arange(n),k)
    classes = np.tile(np.asarray(labels),n)
    sample_weights = (target_prob * weights[:,None]).reshape(-1)
    model.fit(X[row],classes,logisticregression__sample_weight=sample_weights)
    return model


def distillation_probe(meta,ground,sat,observed,yearmonth,split,labels,seed):
    """Cross-fit teacher targets; deploy *satellite only* at test time.

    Distillation is a baseline, not yet a proposed reliability-aware teacher.
    """
    y = meta.crop_label.astype(str).to_numpy()
    train = split["train"]
    groups = block_ids(meta,1.0)
    Xsat = temporal_features(meta,ground,sat,observed,yearmonth,"satellite")
    Xteacher = temporal_features(meta,ground,sat,observed,yearmonth,"aligned")
    all_gold = expert_indices(meta,train)
    train_hard = classifier().fit(Xsat[train],y[train])
    only_gold = classifier().fit(Xsat[all_gold],y[all_gold])
    # Group-held-out teacher soft targets; test has NO ground features.
    try:
        p_teacher = oof_predictions(Xteacher,y,train,groups,labels)
    except ValueError as e:
        return {"skipped":str(e)}
    # Gold training labels remain hard targets.
    for i,rid in enumerate(train):
        if meta.label_source.iloc[rid] == "expert":
            p_teacher[i] = (np.asarray(labels) == y[rid]).astype(float)
    student = soft_student(Xsat[train],p_teacher,labels)
    test = split["test"]
    return {
        "expert_only_satellite":prediction_metrics(y[test],
            probabilities(only_gold,Xsat[test],labels),labels),
        "hard_labels_satellite":prediction_metrics(y[test],
            probabilities(train_hard,Xsat[test],labels),labels),
        "oof_teacher_soft_student":prediction_metrics(y[test],
            probabilities(student,Xsat[test],labels),labels),
        "note":"Teacher soft targets are group-OOF to avoid in-sample teacher leakage. "
               "This is a plain distillation baseline; it does not yet model reliability."
    }


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--metadata",required=True)
    p.add_argument("--sequences",required=True)
    p.add_argument("--output",required=True)
    p.add_argument("--block-degrees",type=float,default=1.)
    p.add_argument("--buffer-km",type=float,default=0.)
    p.add_argument("--seed",type=int,default=13)
    args = p.parse_args()
    meta,ground,sat,obs,ym = load_inputs(args.metadata,args.sequences)
    split = spatial_partition(meta,args.block_degrees,args.buffer_km,args.seed)
    models,fitted,labels,gold = model_probe(meta,ground,sat,obs,ym,split,args.seed)
    results = {
        "protocol":{"training_n":int(len(split["train"])),
                    "expert_train_n":int(len(gold)),
                    "expert_val_n":int(len(split["val"])),
                    "expert_test_n":int(len(split["test"])),
                    "block_degrees":args.block_degrees,"buffer_km":args.buffer_km,
                    "seed":args.seed,
                    "limitations":["This is not trainable cross-attention.",
                                   "This is not proof of geographically calibrated uncertainty.",
                                   "Any synthetic demo output is a smoke test only."]},
        "audit":audit(meta,split), "temporal_models":models
    }
    try:
        results["reliability"] = reliability_probe(
            meta,ground,sat,obs,ym,split,fitted,labels,gold)
    except ValueError as e:
        results["reliability"] = {"skipped":str(e)}
    results["satellite_only_distillation"] = distillation_probe(
        meta,ground,sat,obs,ym,split,labels,args.seed)
    Path(args.output).parent.mkdir(parents=True,exist_ok=True)
    Path(args.output).write_text(json.dumps(results,indent=2))
    print(f"Saved diagnostics to {args.output}")
    print(json.dumps({k:v["macro_f1"] for k,v in models.items()},indent=2))


if __name__=="__main__":
    main()
